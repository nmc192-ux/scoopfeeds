/**
 * musicManifest.js — the radio airs a music bed only when its provenance is written down (#208).
 *
 * DrJ, 22 Oct 2026: beds come from the YouTube Audio Library, "Creative Commons – attribution required"
 * tracks ONLY (they may be used outside YouTube with credit, which covers the X simulcast). Standard
 * Audio Library tracks are YouTube-only and must not be used. No ElevenLabs or other AI-generated music.
 *
 * The manifest is <music dir>/manifest.json (format: docs/radio/music.md):
 *   { "tracks": [ { "file": "evening/calm-river.mp3", "title": "...", "artist": "...",
 *                   "licence": "Creative Commons Attribution 4.0", "credit": "<the library's exact credit text>",
 *                   "downloaded": "2026-10-24", "sha256": "<hex of the downloaded file>",
 *                   "source": "YouTube Audio Library" } ] }
 *
 * REFUSE, DON'T GUESS: a bed with no entry, an incomplete entry, a licence that is not CC attribution,
 * a NonCommercial licence, anything naming an AI music tool, or a file whose sha256 no longer matches,
 * is not aired. `<name>.norm.mp3` (normalizeMusic.mjs) is a loudness copy of `<name>.<ext>`: it airs
 * under its original's entry, and only while that original is still present and still matches.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

export const MANIFEST_FILE = "manifest.json";
export const REQUIRED = ["file", "title", "artist", "licence", "credit", "downloaded", "sha256"];

const CC_BY = /\b(creative commons|cc)[\s\-–—:,]*(by\b|attribution)/i;
const NON_COMMERCIAL = /\b(non[\s-]?commercial|\bnc\b|by-nc)/i;
const AI_MUSIC = /\b(eleven ?labs|suno|udio|aiva|soundraw|mubert|boomy|stable audio|musicgen|ai[\s-]?(generated|music|made)|generated by ai)\b/i;

/** Is this licence text a Creative Commons attribution licence we may air on YouTube AND X? */
export function isCcAttribution(licence) {
  const s = String(licence || "");
  return CC_BY.test(s) && !NON_COMMERCIAL.test(s);
}

/** Problems with one manifest entry (empty array = complete and acceptable). Does not touch the disk. */
export function entryProblems(e) {
  if (!e || typeof e !== "object") return ["not an object"];
  const p = [];
  for (const k of REQUIRED) if (!String(e[k] ?? "").trim()) p.push(`${k} missing`);
  if (e.licence && !isCcAttribution(e.licence)) p.push(`licence "${e.licence}" is not Creative Commons attribution (commercial use allowed)`);
  if (e.sha256 && !/^[0-9a-f]{64}$/i.test(String(e.sha256))) p.push("sha256 is not 64 hex characters");
  if (e.downloaded && !Number.isFinite(Date.parse(e.downloaded))) p.push(`downloaded "${e.downloaded}" is not a date`);
  const text = [e.title, e.artist, e.licence, e.credit, e.source, e.tool].filter(Boolean).join(" ");
  if (AI_MUSIC.test(text)) p.push("names an AI music tool: AI-generated music never airs on the radio");
  if (e.source && !/youtube audio library/i.test(e.source)) p.push(`source "${e.source}" is not the YouTube Audio Library`);
  return p;
}

const norm = (rel) => String(rel || "").replace(/\\/g, "/").replace(/^\.\//, "");

/** Read <dir>/manifest.json. Never throws: an unreadable manifest is an empty one, with the reason. */
export function loadManifest(dir) {
  const f = path.join(dir, MANIFEST_FILE);
  let raw;
  try { raw = JSON.parse(fs.readFileSync(f, "utf8")); }
  catch (e) { return { byFile: new Map(), problems: [fs.existsSync(f) ? `${MANIFEST_FILE} unreadable: ${e.message}` : `${MANIFEST_FILE} missing`] }; }
  const list = Array.isArray(raw) ? raw : Array.isArray(raw?.tracks) ? raw.tracks : [];
  const byFile = new Map(), problems = [];
  for (const e of list) {
    const bad = entryProblems(e);
    if (bad.length) { problems.push(`${e?.file || "(no file)"}: ${bad.join("; ")}`); continue; }
    byFile.set(norm(e.file), { ...e, file: norm(e.file) });
  }
  return { byFile, problems };
}

// sha256 is cached by path + size + mtime: the 24/7 playout asks every 30 s.
const hashCache = new Map();
export function sha256File(file) {
  const st = fs.statSync(file);
  const key = `${file}|${st.size}|${st.mtimeMs}`;
  if (hashCache.has(key)) return hashCache.get(key);
  const h = crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
  hashCache.set(key, h);
  return h;
}

/** The original a bed stands for: "x.norm.mp3" -> the sibling "x.<ext>" that exists (not itself a .norm.mp3). */
function originalOf(abs) {
  if (!abs.endsWith(".norm.mp3")) return abs;
  const stem = path.basename(abs).slice(0, -".norm.mp3".length);
  const d = path.dirname(abs);
  let names = [];
  try { names = fs.readdirSync(d); } catch { return null; }
  const hit = names.find((n) => !n.endsWith(".norm.mp3") && n.replace(/\.[^.]+$/, "") === stem);
  return hit ? path.join(d, hit) : null;
}

/**
 * The manifest entry that clears this bed for air, or { ok:false, why }.
 * @param {string} abs    absolute path of the bed (under dir)
 * @param {string} dir    the music dir holding manifest.json
 */
export function clearBed(abs, dir, manifest = loadManifest(dir)) {
  const orig = originalOf(abs);
  if (!orig) return { ok: false, why: `${path.basename(abs)}: its original file is gone` };
  const rel = norm(path.relative(dir, orig));
  const e = manifest.byFile.get(rel);
  if (!e) return { ok: false, why: `${rel}: no complete manifest entry` };
  let have;
  try { have = sha256File(orig); } catch (err) { return { ok: false, why: `${rel}: unreadable (${err.message})` }; }
  if (have.toLowerCase() !== String(e.sha256).toLowerCase()) return { ok: false, why: `${rel}: sha256 does not match the manifest` };
  return { ok: true, entry: e };
}

/** "Music: Artist – Track", the small on-screen credit for a music break. */
export const screenCredit = (e) => (e ? `Music: ${e.artist} – ${e.title}` : null);

/** The library's exact credit text for each track, de-duplicated, in order. For broadcast descriptions. */
export function creditLines(entries) {
  const seen = new Set(), out = [];
  for (const e of entries || []) { const c = String(e?.credit || "").trim(); if (c && !seen.has(c)) { seen.add(c); out.push(c); } }
  return out;
}
